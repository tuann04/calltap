#!/usr/bin/env bash
# Generate short-lived Cloudflare Realtime TURN credentials and persist them to
# deploy/cloudflare/turn.env so docker-compose picks them up on container restart.
# Schedule: at boot and daily (see turn-rotate.timer).
set -euo pipefail

# TURN key API token + key id from `cf realtime turn keys` (mode 600 on this file)
CREDENTIALS_FILE="${CREDENTIALS_FILE:-/etc/calltap/turn-key.env}"
# shellcheck disable=SC1090
[ -f "$CREDENTIALS_FILE" ] && . "$CREDENTIALS_FILE"
: "${TURN_KEY_ID:?TURN_KEY_ID missing in $CREDENTIALS_FILE}"
: "${TURN_API_TOKEN:?TURN_API_TOKEN missing in $CREDENTIALS_FILE}"
: "${STATE_FILE:=/var/lib/calltap/turn.env}"

TTL_SECONDS="${TTL_SECONDS:-86400}" # Cloudflare TURN max TTL is 48h; rotate daily

mkdir -p "$(dirname "$STATE_FILE")"
TMP="$(mktemp "$(dirname "$STATE_FILE")/.turn.env.XXXXXX")"
trap 'rm -f "$TMP"' EXIT

JSON="$(curl -fsS --max-time 15 \
  -X POST "https://rtc.live.cloudflare.com/v1/turn/keys/${TURN_KEY_ID}/credentials/generate" \
  -H "Authorization: Bearer ${TURN_API_TOKEN}" \
  -H "Content-Type: application/json" \
  -d "{\"ttl\": ${TTL_SECONDS}}")"

python3 - "$STATE_FILE" "$TMP" "$JSON" <<'PY'
import json, sys

state_file, tmp, payload = sys.argv[1], sys.argv[2], json.loads(sys.argv[3])
ice = payload["iceServers"]
urls, username, credential = ice["urls"], ice["username"], ice["credential"]

frontend = [{"urls": urls, "username": username, "credential": credential}]
# Backend only needs TURN; drop STUN to keep server-side candidates simple.
backend = [e for e in frontend if any(u.startswith("turn") for u in e["urls"])]

with open(tmp, "w") as f:
    f.write("# Generated by turn-rotate.sh; do not edit.\n")
    f.write(f"# Rotated: {__import__('datetime').datetime.now(datetime.timezone.utc).isoformat()}\n")
    f.write(f"NEKO_TURN_TTL={TTL_SECONDS}\n")
    f.write("NEKO_TURN_FRONTEND=" + json.dumps(frontend, separators=(",", ":")) + "\n")
    f.write("NEKO_TURN_BACKEND=" + json.dumps(backend, separators=(",", ":")) + "\n")
PY

chmod 600 "$TMP"
mv "$TMP" "$STATE_FILE"
echo "TURN credentials rotated -> $STATE_FILE (ttl=${TTL_SECONDS}s)"
